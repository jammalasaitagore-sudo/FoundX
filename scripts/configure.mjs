/**
 * FoundX - one-command environment setup.
 *
 * Writes .env for you, so you never have to edit a file by hand:
 *
 *   node scripts/configure.mjs <SUPABASE_URL> <PUBLISHABLE_KEY> <SECRET_KEY>
 *
 * or just run `node scripts/configure.mjs` and paste the three values when
 * prompted. The secret key is never printed back to the terminal.
 */
import fs from 'node:fs';
import path from 'node:path';
import readline from 'node:readline/promises';
import { stdin, stdout } from 'node:process';

const envPath = path.join(process.cwd(), '.env');

function mask(value) {
  if (!value) return '(empty)';
  if (value.length <= 12) return '***';
  return `${value.slice(0, 10)}...${value.slice(-4)}`;
}

async function ask(question, fallback) {
  const rl = readline.createInterface({ input: stdin, output: stdout });
  const answer = (await rl.question(`${question}${fallback ? ` [${fallback}]` : ''}: `)).trim();
  rl.close();
  return answer || fallback || '';
}

async function main() {
  let [url, anonKey, secretKey] = process.argv.slice(2);

  console.log('\nFoundX - environment setup\n');

  if (!url) url = await ask('Supabase project URL (https://xxxx.supabase.co)');
  if (!anonKey) anonKey = await ask('Publishable key (sb_publishable_...)');
  if (!secretKey) secretKey = await ask('Secret key (sb_secret_...)');

  url = url.trim().replace(/\/+$/, '');
  anonKey = anonKey.trim();
  secretKey = secretKey.trim();

  const problems = [];
  if (!/^https:\/\/.+\.supabase\.(co|in)$/.test(url)) {
    problems.push('SUPABASE_URL must look like https://your-ref.supabase.co');
  }
  if (anonKey.length < 20) problems.push('The publishable key looks too short.');
  if (secretKey.length < 20) problems.push('The secret key looks too short.');
  if (anonKey === secretKey) problems.push('The publishable and secret keys are the same value.');

  if (problems.length) {
    console.error('\nCould not write .env:');
    problems.forEach((problem) => console.error(`  - ${problem}`));
    console.error('\nCopy the values again from Supabase -> Project Settings -> API keys.\n');
    process.exit(1);
  }

  const existing = fs.existsSync(envPath) ? fs.readFileSync(envPath, 'utf8') : '';
  const keep = (key, fallbackValue) => {
    const match = existing.match(new RegExp(`^${key}=(.*)$`, 'm'));
    return match && match[1].trim() ? match[1].trim() : fallbackValue;
  };

  const contents = `# FoundX environment - generated by scripts/configure.mjs
# This file is git-ignored. Never commit it or paste it into the report.

PORT=${keep('PORT', '4000')}
NODE_ENV=${keep('NODE_ENV', 'development')}
CORS_ORIGINS=${keep('CORS_ORIGINS', 'http://localhost:4000,http://127.0.0.1:4000')}

SUPABASE_URL=${url}
SUPABASE_ANON_KEY=${anonKey}
SUPABASE_SERVICE_ROLE_KEY=${secretKey}

SUPABASE_STORAGE_BUCKET=${keep('SUPABASE_STORAGE_BUCKET', 'item-images')}
MAX_UPLOAD_MB=${keep('MAX_UPLOAD_MB', '5')}
`;

  fs.writeFileSync(envPath, contents, { mode: 0o600 });

  console.log('\n.env written to ' + envPath);
  console.log('  SUPABASE_URL                : ' + url);
  console.log('  SUPABASE_ANON_KEY           : ' + mask(anonKey));
  console.log('  SUPABASE_SERVICE_ROLE_KEY   : ' + mask(secretKey));
  console.log('\nNext commands:');
  console.log('  npm run seed     # creates the demo accounts and 12 sample items');
  console.log('  npm start        # http://localhost:4000/api/health');
  console.log('  npm run smoke    # runs the automated API checks\n');
}

main().catch((error) => {
  console.error('\nSetup failed:', error.message);
  process.exit(1);
});
